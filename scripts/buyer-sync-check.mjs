#!/usr/bin/env node
// buyer-sync detector. Runs after every commit (via .githooks/post-commit) and
// flags when the commit touched something buyer-facing, so the kit's setup
// guide / README / onboarding never silently drift behind the code.
//
// It does NOT change files and does NOT call an LLM — it just prints a one-line
// advisory pointing at the /buyer-sync skill, which does the actual updating.
//
// Self-guards: exits silently inside the buyer kit (where publish-kit.ts has
// been stripped), so buyers never see this.
import { execSync } from "node:child_process";
import { existsSync } from "node:fs";

// Only run in the SOURCE repo. The kit strips scripts/publish-kit.ts.
if (!existsSync(new URL("./publish-kit.ts", import.meta.url))) process.exit(0);

function git(args) {
  try { return execSync(`git ${args}`, { encoding: "utf8" }).trim(); }
  catch { return ""; }
}

// Don't nag on the skill's own sync commits (avoids a flag→sync→flag spiral).
const lastMsg = git("log -1 --pretty=%s");
if (/^chore\(buyer-sync\)/.test(lastMsg)) process.exit(0);

const range = process.argv[2] || "HEAD~1..HEAD";
const changed = git(`diff --name-only ${range}`).split("\n").filter(Boolean);
if (changed.length === 0) process.exit(0);

const has = (re) => changed.some((f) => re.test(f));

// Map changed paths → buyer surfaces that may now be stale.
const flags = [];
if (has(/^src\/lib\/alfred\/tools\.ts$/))            flags.push("tools changed → README tool count / guide integrations");
if (has(/^vercel\.json$/))                            flags.push("crons changed → MUST stay ≤2 (Hobby); guide cron copy");
if (has(/^supabase\/(schema\.sql|migrations\/)/))     flags.push("schema/migrations changed → setup.sql (regenerated by publish-kit)");
if (has(/^\.env\.local\.example$/))                   flags.push("env template changed → init.ts secret/prompt + guide");
if (has(/^src\/app\/\(protected\)\/d\/[^/]+\//))      flags.push("a dashboard page changed/added → guided tour + onboarding");
if (has(/^src\/lib\/alfred\//))                        flags.push("an Alfred capability changed → README 'What's inside' + onboarding");
if (has(/^src\/config\.ts$/))                          flags.push("config defaults changed → publish-kit neutralization list");

if (flags.length === 0) process.exit(0);

const Y = "\x1b[33m", D = "\x1b[2m", R = "\x1b[0m";
console.log(`\n${Y}🛍  buyer-sync:${R} this commit may have left the buyer kit stale:`);
for (const f of flags) console.log(`   ${D}•${R} ${f}`);
console.log(`   ${D}→ run${R} /buyer-sync ${D}to update the guide, README, onboarding & kit.${R}\n`);
process.exit(0);
